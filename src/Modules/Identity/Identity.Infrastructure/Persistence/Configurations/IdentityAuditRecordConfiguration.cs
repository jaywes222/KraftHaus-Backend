using System.Text.Json;
using Identity.Infrastructure.Auditing;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.ChangeTracking;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using Microsoft.EntityFrameworkCore.Storage.ValueConversion;

namespace Identity.Infrastructure.Persistence.Configurations;

public sealed class IdentityAuditRecordConfiguration
    : IEntityTypeConfiguration<IdentityAuditRecord>
{
    public void Configure(
        EntityTypeBuilder<IdentityAuditRecord> builder)
    {
        builder.ToTable(IdentityAuditRecord.TableName);

        builder.HasKey(x => x.Id);

        // Ids come from the domain event (or a v7 Guid for rejections); never generated by the database.
        builder.Property(x => x.Id)
            .ValueGeneratedNever();

        builder.Property(x => x.OccurredAt)
            .IsRequired();

        builder.Property(x => x.Module)
            .HasMaxLength(IdentityAuditRecord.ModuleMaxLength)
            .IsRequired();

        builder.Property(x => x.Action)
            .HasMaxLength(IdentityAuditRecord.ActionMaxLength)
            .IsRequired();

        builder.Property(x => x.Outcome)
            .HasMaxLength(IdentityAuditRecord.EnumMaxLength)
            .IsRequired();

        builder.Property(x => x.ActorType)
            .HasMaxLength(IdentityAuditRecord.EnumMaxLength)
            .IsRequired();

        builder.Property(x => x.ActorId)
            .HasMaxLength(IdentityAuditRecord.ActorIdMaxLength);

        builder.Property(x => x.ActorSessionId)
            .HasMaxLength(IdentityAuditRecord.ActorIdMaxLength);

        builder.Property(x => x.SubjectUserId);

        builder.Property(x => x.TenantId);

        builder.Property(x => x.TargetType)
            .HasMaxLength(IdentityAuditRecord.TargetTypeMaxLength);

        builder.Property(x => x.TargetId)
            .HasMaxLength(IdentityAuditRecord.TargetIdMaxLength);

        builder.Property(x => x.ReasonCode)
            .HasMaxLength(IdentityAuditRecord.ReasonCodeMaxLength);

        builder.Property(x => x.TraceId)
            .HasMaxLength(IdentityAuditRecord.TraceIdMaxLength);

        builder.Property(x => x.RequestId)
            .HasMaxLength(IdentityAuditRecord.RequestIdMaxLength);

        builder.Property(x => x.Metadata)
            .HasColumnType("jsonb")
            .HasConversion(
                new ValueConverter<IReadOnlyDictionary<string, string>, string>(
                    value => JsonSerializer.Serialize(value, (JsonSerializerOptions?)null),
                    json => Deserialize(json)),
                new ValueComparer<IReadOnlyDictionary<string, string>>(
                    (left, right) => ReferenceEquals(left, right),
                    value => value.Count,
                    value => value))
            .IsRequired();

        builder.HasIndex(x => x.OccurredAt)
            .IsDescending()
            .HasDatabaseName("IX_security_audit_log_OccurredAt");

        builder.HasIndex(x => new { x.SubjectUserId, x.OccurredAt })
            .IsDescending(false, true)
            .HasDatabaseName("IX_security_audit_log_SubjectUserId_OccurredAt");

        builder.HasIndex(x => new { x.ActorId, x.OccurredAt })
            .IsDescending(false, true)
            .HasDatabaseName("IX_security_audit_log_ActorId_OccurredAt");

        builder.HasIndex(x => new { x.Action, x.OccurredAt })
            .IsDescending(false, true)
            .HasDatabaseName("IX_security_audit_log_Action_OccurredAt");

        builder.HasIndex(x => new { x.TargetType, x.TargetId })
            .HasDatabaseName("IX_security_audit_log_Target");

        builder.HasIndex(x => x.TraceId)
            .HasDatabaseName("IX_security_audit_log_TraceId");

        builder.HasIndex(x => new { x.TenantId, x.OccurredAt })
            .IsDescending(false, true)
            .HasDatabaseName("IX_security_audit_log_TenantId_OccurredAt");
    }

    private static Dictionary<string, string> Deserialize(string json) =>
        JsonSerializer.Deserialize<Dictionary<string, string>>(json)
        ?? new Dictionary<string, string>(StringComparer.Ordinal);
}
