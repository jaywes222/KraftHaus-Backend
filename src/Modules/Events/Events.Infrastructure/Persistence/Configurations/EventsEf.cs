using Common.Domain.Entities;
using Common.Domain.StronglyTypedIds;
using Common.Infrastructure.Persistence.ValueConverters;
using Events.Domain.Venues;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using Microsoft.EntityFrameworkCore.Storage.ValueConversion;

namespace Events.Infrastructure.Persistence.Configurations;

/// <summary>Mapping helpers shared by the Events configurations.</summary>
internal static class EventsEf
{
    private static readonly ValueConverter<ApplicationUserId?, Guid?> UserIdConverter = new(
        id => id.HasValue ? id.Value.Value : null,
        value => value.HasValue ? new ApplicationUserId(value.Value) : null);

    /// <summary>Strongly typed id key: client-generated v7 Guid, never generated by the database.</summary>
    public static void ConfigureKey<TEntity, TId>(EntityTypeBuilder<TEntity> builder)
        where TEntity : AuditableEntity<TId>
        where TId : struct, IStronglyTypedId
    {
        builder.HasKey(x => x.Id);

        builder.Property(x => x.Id)
            .HasConversion(new StronglyTypedIdValueConverter<TId>())
            .ValueGeneratedNever();
    }

    /// <summary>CreatedOn/By, LastModifiedOn/By (stamped by ApplyAuditingInterceptor).</summary>
    public static void ConfigureAudit<TEntity>(EntityTypeBuilder<TEntity> builder)
        where TEntity : AuditableEntity
    {
        builder.Property(x => x.CreatedOn).IsRequired();
        builder.Property(x => x.CreatedBy).HasConversion(UserIdConverter);
        builder.Property(x => x.LastModifiedOn);
        builder.Property(x => x.LastModifiedBy).HasConversion(UserIdConverter);
    }

    /// <summary>Aggregate version: incremented by every raised domain event, used as the concurrency token.</summary>
    public static void ConfigureAggregateVersion<TEntity>(EntityTypeBuilder<TEntity> builder)
        where TEntity : class
    {
        builder.Property("Version")
            .HasColumnName("aggregate_version")
            .IsConcurrencyToken();
    }

    /// <summary>Columns of a <see cref="VenueDetails" /> owned value.</summary>
    public static void ConfigureVenueDetails<TOwner>(
        OwnedNavigationBuilder<TOwner, VenueDetails> details,
        string prefix)
        where TOwner : class
    {
        details.Property(x => x.Name)
            .HasColumnName($"{prefix}Name")
            .HasMaxLength(VenueDetails.NameMaxLength)
            .IsRequired();

        details.Property(x => x.AddressLine)
            .HasColumnName($"{prefix}AddressLine")
            .HasMaxLength(VenueDetails.AddressMaxLength);

        details.Property(x => x.City)
            .HasColumnName($"{prefix}City")
            .HasMaxLength(VenueDetails.CityMaxLength);

        details.Property(x => x.MapUrl)
            .HasColumnName($"{prefix}MapUrl")
            .HasMaxLength(2048);

        details.Property(x => x.Directions)
            .HasColumnName($"{prefix}Directions")
            .HasMaxLength(VenueDetails.DirectionsMaxLength);
    }
}
